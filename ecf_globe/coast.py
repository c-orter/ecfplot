def _cross(a, b, c):
    """> 0 if a -> b -> c turns left (counter-clockwise)."""
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


def _in_triangle(a, b, c, q):
    """True if q is inside (or on) the counter-clockwise triangle a, b, c."""
    return min(_cross(a, b, q), _cross(b, c, q), _cross(c, a, q)) >= 0


def _ear_clip(p):
    """Triangulate a simple polygon (n, 2) -> list of (i, j, k) vertex indices."""
    idx = list(range(len(p)))
    shoelace = np.sum(p[:, 0] * np.roll(p[:, 1], -1) - np.roll(p[:, 0], -1) * p[:, 1])
    if shoelace < 0:  # make it counter-clockwise
        idx.reverse()
    tris = []
    while len(idx) > 3:
        for m in range(len(idx)):
            i, j, k = idx[m - 1], idx[m], idx[(m + 1) % len(idx)]
            if _cross(p[i], p[j], p[k]) < 0:
                continue  # reflex corner
            others = [q for q in idx if q not in (i, j, k)]
            if any(_in_triangle(p[i], p[j], p[k], p[q]) for q in others):
                continue  # another vertex inside: not an ear
            tris.append((i, j, k))  # zero-area if i, j, k are in line: harmless
            del idx[m]
            break
        else:
            raise ValueError("COAST outline crosses itself; cannot fill it")
    return tris + [tuple(idx)]


def _length(a, b):
    """Rough great-circle length, in degrees, between two (lon, lat) points."""
    return np.hypot((b[0] - a[0]) * np.cos(np.radians((a[1] + b[1]) / 2)), b[1] - a[1])


def _split(t, step):
    """Bisect a (3, 2) triangle across its longest edge until all edges <= step."""
    m = int(np.argmax([_length(t[m - 1], t[m]) for m in range(3)]))
    a, b, c = t[m - 1], t[m], t[m - 2]  # a-b is the longest edge
    if _length(a, b) <= step:
        return [t]
    mid = (a + b) / 2
    return _split(np.array([a, mid, c]), step) + _split(np.array([mid, b, c]), step)


@lru_cache  # ~0.4 s; call land_trace.cache_clear() after changing COAST
def land_trace(units="km", ellipsoid=True):
    """Filled COAST outlines as a non-hoverable Mesh3d, 6 km above the surface.

    Each outline is triangulated in lon/lat, then the triangles are split to
    at most 4 degrees so they follow the curved surface.
    """
    tris = []
    for outline in COAST.values():
        p = np.array(outline, float)
        if abs(p[0, 0] - p[-1, 0]) > 180:  # spans every longitude: close via the pole
            pole = -90 if p[:, 1].mean() < 0 else 90
            p = np.vstack([p, [p[-1, 0], pole], [p[0, 0], pole]])
        for t in _ear_clip(p):
            tris += _split(p[list(t)], 4.0)
    # triangles share corners: send each point once and index it
    lonlat, corner = np.unique(np.vstack(tris), axis=0, return_inverse=True)
    lon, lat = lonlat.T
    x, y, z = geodetic_to_ecf(lat, lon, 6e3 / UNITS[units], units, ellipsoid)
    i, j, k = corner.reshape(-1, 3).T
    return go.Mesh3d(
        x=np.round(x, 1),  # 0.1 km (or m): halves the JSON
        y=np.round(y, 1),
        z=np.round(z, 1),
        i=i,
        j=j,
        k=k,
        color="#8fcf8f",
        hoverinfo="skip",
        name="Land",
        showlegend=False,
        **LIGHTING,
    )
